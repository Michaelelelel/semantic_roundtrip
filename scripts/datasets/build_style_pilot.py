"""Sample held-out titles for the four-style pilot from the frozen candidate pool."""

import csv
import hashlib
import json
import random
from argparse import ArgumentParser
from collections import Counter
from pathlib import Path

import yaml

DOMAINS = ("songs", "movies", "bands")
DATASETS = Path("configs/datasets")


def select_pilot(
    rows: list[dict[str, str]],
    excluded: set[str],
    *,
    titles_per_domain: int = 30,
    seed: int = 20260903,
) -> list[dict[str, str]]:
    """Shuffle each domain once, excluding held-out IDs and repeated song artists."""
    if titles_per_domain < 1:
        raise ValueError("titles_per_domain must be positive.")
    selected = []
    for domain in DOMAINS:
        candidates = sorted(
            (
                row
                for row in rows
                if row["domain"] == domain and row["id"] not in excluded
            ),
            key=lambda row: (int(row["source_rank"]), row["source_id"], row["id"]),
        )
        random.Random(f"{seed}:{domain}").shuffle(candidates)
        domain_rows = []
        artists: set[str] = set()
        for row in candidates:
            artist = row["selection_group"] if domain == "songs" else ""
            if domain == "songs" and not artist:
                raise ValueError(f"Missing primary artist for {row['id']}.")
            if artist and artist in artists:
                continue
            domain_rows.append(row)
            artists.add(artist)
            if len(domain_rows) == titles_per_domain:
                break
        if len(domain_rows) != titles_per_domain:
            raise ValueError(
                f"Only {len(domain_rows)} eligible {domain} titles remain."
            )
        selected.extend(
            sorted(domain_rows, key=lambda row: (int(row["source_rank"]), row["id"]))
        )
    return selected


def main() -> None:
    parser = ArgumentParser(description=__doc__)
    parser.add_argument(
        "--candidates", type=Path, default=DATASETS / "eligible_top300_v1_sources.csv"
    )
    parser.add_argument(
        "--exclude",
        type=Path,
        nargs="+",
        default=[
            DATASETS / "final_titles_v1.yaml",
            DATASETS / "illustratable_titles_v1.yaml",
        ],
    )
    parser.add_argument("--titles-per-domain", type=int, default=30)
    parser.add_argument("--seed", type=int, default=20260903)
    parser.add_argument(
        "--output", type=Path, default=DATASETS / "style_pilot_titles_v1.yaml"
    )
    args = parser.parse_args()
    with args.candidates.open(encoding="utf-8", newline="") as source:
        reader = csv.DictReader(source)
        rows = list(reader)
        fields = reader.fieldnames
    excluded = {
        item["id"]
        for path in args.exclude
        for item in yaml.safe_load(path.read_text(encoding="utf-8"))["items"]
    }
    selected = select_pilot(
        rows, excluded, titles_per_domain=args.titles_per_domain, seed=args.seed
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    profile = {
        "schema_version": 1,
        "dataset_id": args.output.stem,
        "items": [
            {key: row[key] for key in ("id", "domain", "title")} for row in selected
        ],
    }
    args.output.write_text(
        "# Generated by scripts/datasets/build_style_pilot.py.\n"
        + yaml.safe_dump(profile, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    report = args.output.with_name(f"{args.output.stem}_sources.csv")
    with report.open("w", encoding="utf-8", newline="") as output:
        writer = csv.DictWriter(output, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(selected)
    inputs = [args.candidates, *args.exclude]
    manifest = {
        "method": "held_out_domain_shuffle_artist_unique_v1",
        "script": "scripts/datasets/build_style_pilot.py",
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "seed": args.seed,
        "domain_order": list(DOMAINS),
        "titles_per_domain": args.titles_per_domain,
        "counts": dict(Counter(row["domain"] for row in selected)),
        "inputs": [
            {"path": str(path), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
            for path in inputs
        ],
        "excluded_datasets": [str(path) for path in args.exclude],
        "dataset_sha256": hashlib.sha256(args.output.read_bytes()).hexdigest(),
        "sources_sha256": hashlib.sha256(report.read_bytes()).hexdigest(),
    }
    args.output.with_suffix(".json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )
    print(
        f"Selected {len(selected)} pilot titles: {dict(Counter(row['domain'] for row in selected))}"
    )
    print(args.output)
    print(report)


if __name__ == "__main__":
    main()
